#include "libft.h"

int	ft_putnbr_dec(int n)
{
	int	count;

	count = 0;
	if (n == -2147483648)
	{
		write (2, "-2147483648", 11);
		return (11);
	}
	if (n < 0)
	{
		ft_putchar('-');
		n = -n;
		count++;
	}
	if (n > 9)
		count += ft_putnbr_dec(n / 10);
	count += ft_putchar((n % 10 + 48));
	return (count);
}
